package pkgclass

import (
	"go/parser"
	"go/token"
	"testing"
)

func TestMockFileName(t *testing.T) {
	for path, want := range map[string]bool{
		"/x/store_mock.go": true,
		"/x/zzz_store.go":  true,
		"zzz_store.go":     true,
		"/x/store.go":      false,
		"/x/mock_store.go": false, // a header, not the name, marks this one
		"/x/zzz/store.go":  false,
	} {
		if got := MockFileName(path); got != want {
			t.Errorf("MockFileName(%q) = %v, want %v", path, got, want)
		}
	}
}

func TestMockHeader(t *testing.T) {
	cases := []struct {
		name, src string
		want      bool
	}{
		{"mockgen", "// Code generated by MockGen. DO NOT EDIT.\n// Source: a.go\n\npackage a\n", true},
		{"mockgen with doc after header", "// Code generated by MockGen. DO NOT EDIT.\n\n// Package a is x.\npackage a\n", true},
		{"mockery v2", "// Code generated by mockery v2.43.0. DO NOT EDIT.\n\npackage a\n", true},
		{"mockery v3", "// Code generated by mockery; DO NOT EDIT.\n\npackage a\n", true},
		{"minimock", "// Code generated by http://github.com/gojuno/minimock (v3.4.7). DO NOT EDIT.\n\npackage a\n", true},
		{"minimock dev", "// Code generated by http://github.com/gojuno/minimock (dev). DO NOT EDIT.\n\npackage a\n", true},
		{"header not first comment", "// Copyright x.\n\n// Code generated by MockGen. DO NOT EDIT.\n\npackage a\n", true},
		{"counterfeiter", "// Code generated by counterfeiter. DO NOT EDIT.\n\npackage a\n", true},
		{"moq", "// Code generated by moq; DO NOT EDIT.\n\npackage a\n", true},
		{"moq word boundary", "// Code generated by moqs; DO NOT EDIT.\n\npackage a\n", false},
		{"protoc", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n", false},
		{"gqlgen", "// Code generated by github.com/99designs/gqlgen, DO NOT EDIT.\n\npackage a\n", false},
		{"handwritten", "package a\n", false},
		{"doc comment names mockgen", "// Package a wraps the output of mockgen.\npackage a\n", false},
		{"header text after package clause", "package a\n\n// Code generated by MockGen. DO NOT EDIT.\nfunc F() {}\n", false},
		{"not a header line", "// Do not say Code generated by MockGen. DO NOT EDIT.\n\npackage a\n", false},
		{"word boundary", "// Code generated by mockeryfoo. DO NOT EDIT.\n\npackage a\n", false},
		{"missing DO NOT EDIT", "// Code generated by MockGen.\n\npackage a\n", false},
		{"other minimock path", "// Code generated by http://github.com/gojuno/minimocker. DO NOT EDIT.\n\npackage a\n", false},
	}
	for _, c := range cases {
		f, err := parser.ParseFile(token.NewFileSet(), "a.go", c.src, parser.ParseComments)
		if err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		if got := MockHeader(f); got != c.want {
			t.Errorf("%s: MockHeader = %v, want %v", c.name, got, c.want)
		}
	}
	if MockHeader(nil) {
		t.Error("a nil file is not a mock")
	}
}
